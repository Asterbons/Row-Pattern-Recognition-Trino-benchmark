#!/usr/bin/env python3
# run_scalability.py
# Orchestrates scalability benchmarks across multiple dataset sizes.
# For each size: generates init SQL, starts Docker services, runs benchmark, tears down.
#
# Usage:
#   python run_scalability.py
#   python run_scalability.py --sizes 1000,10000,100000

import argparse
import os
import subprocess
import sys
import time

import requests

SIZES = [1_000, 10_000, 100_000, 1_000_000, 10_000_000]
PROJECT_DIR = os.path.dirname(os.path.abspath(__file__))
INIT_SQL_PATH = os.path.join(PROJECT_DIR, 'init-scripts-scalability', 'init-db.sql')
COMPOSE_FILE = os.path.join(PROJECT_DIR, 'docker-compose.scalability.yml')
TRINO_URL = 'http://localhost:8081/v1/info'
TRINO_POLL_INTERVAL_S = 5
TRINO_POLL_TIMEOUT_S = 120
DATA_READY_TIMEOUT_S = 600  # wait up to 10 min for large CSV COPY + PG restart


def generate_init_sql(size):
    csv_path = f'/project_data/datasets/scalability/n_{size}/crime_data.csv'
    sql = f"""-- This file is auto-generated by run_scalability.py
-- Do not edit manually.

CREATE TABLE IF NOT EXISTS crime_data (
    id            INTEGER PRIMARY KEY,
    district      VARCHAR(100),
    datetime      TIMESTAMP,
    primary_type  VARCHAR(50),
    lat           DOUBLE PRECISION,
    lon           DOUBLE PRECISION
);

COPY crime_data (id, district, datetime, primary_type, lat, lon)
FROM '{csv_path}'
DELIMITER ','
CSV HEADER;
"""
    with open(INIT_SQL_PATH, 'w') as f:
        f.write(sql)
    print(f"  [init-sql] {INIT_SQL_PATH} -> n_{size}/crime_data.csv")


def docker_compose(args, check=True):
    cmd = ['docker-compose', '-f', COMPOSE_FILE] + args
    print(f"  [docker] {' '.join(args)}")
    return subprocess.run(cmd, cwd=PROJECT_DIR, check=check)


def wait_for_trino():
    print(f"  [trino] Polling until ready (timeout={TRINO_POLL_TIMEOUT_S}s)...")
    deadline = time.time() + TRINO_POLL_TIMEOUT_S
    while time.time() < deadline:
        try:
            resp = requests.get(TRINO_URL, timeout=5)
            if resp.status_code == 200 and not resp.json().get('starting', True):
                print("  [trino] Ready!")
                return True
        except Exception:
            pass
        time.sleep(TRINO_POLL_INTERVAL_S)
    return False


def wait_for_data(expected_size):
    """Block until crime_data has the expected row count (or timeout).

    Needed because PostgreSQL's Docker entrypoint does a planned restart after
    running init scripts. For large CSVs the COPY can take 30-60+ seconds, so
    the Trino healthcheck passes while PG is still loading — then PG restarts
    for normal operation, breaking all open connections. We poll until the data
    is confirmed present before handing off to the benchmark.
    """
    import trino as trino_mod
    print(f"  [data] Waiting for {expected_size:,} rows in crime_data "
          f"(timeout={DATA_READY_TIMEOUT_S}s)...")
    deadline = time.time() + DATA_READY_TIMEOUT_S
    last_count = None
    while time.time() < deadline:
        try:
            conn = trino_mod.dbapi.connect(
                host='localhost', port=8081, user='admin',
                catalog='postgres', schema='public',
            )
            cur = conn.cursor()
            cur.execute("SELECT count(*) FROM crime_data")
            count = cur.fetchone()[0]
            conn.close()
            if count >= expected_size * 0.999:
                print(f"  [data] Ready: {count:,} rows")
                return True
            if count != last_count:
                print(f"  [data] {count:,} / {expected_size:,} rows loaded...")
                last_count = count
        except Exception as e:
            print(f"  [data] Not ready yet ({e})")
        time.sleep(TRINO_POLL_INTERVAL_S)
    print(f"  [data] Timed out waiting for data")
    return False


def run_benchmark_for_size(size):
    cmd = [
        'docker-compose', '-f', COMPOSE_FILE,
        'run', '--rm', 'benchmark',
        'python', 'benchmark.py', '--dataset-size', str(size),
    ]
    print(f"  [benchmark] Starting benchmark (size={size:,})...")
    result = subprocess.run(cmd, cwd=PROJECT_DIR)
    return result.returncode == 0


def main():
    parser = argparse.ArgumentParser(description='Scalability benchmark orchestrator')
    parser.add_argument('--sizes', type=str, default=None,
                        help='Comma-separated sizes to run (default: all)')
    args = parser.parse_args()

    sizes = [int(s.strip()) for s in args.sizes.split(',')] if args.sizes else SIZES

    print("=" * 60)
    print("Scalability Benchmark Orchestrator")
    print("=" * 60)
    print(f"Sizes: {[f'{s:,}' for s in sizes]}")
    print()

    failed = []

    for size in sizes:
        print(f"\n{'=' * 60}")
        print(f"SIZE: {size:,} rows")
        print(f"{'=' * 60}")

        csv_path = os.path.join(
            PROJECT_DIR, 'datasets', 'scalability', f'n_{size}', 'crime_data.csv'
        )
        if not os.path.exists(csv_path):
            print(f"  [ERROR] Dataset missing: {csv_path}")
            print(f"          Run: python Generator/generate_all_scales.py")
            failed.append(size)
            continue

        # 1. Generate per-size init SQL
        generate_init_sql(size)

        # 2. Start services
        docker_compose(['up', '-d'])

        # 3. Wait for Trino coordinator
        if not wait_for_trino():
            print(f"  [ERROR] Trino not ready after {TRINO_POLL_TIMEOUT_S}s")
            docker_compose(['down', '-v'], check=False)
            failed.append(size)
            continue

        # 4. Wait until data is fully loaded (blocks through PG init restart)
        if not wait_for_data(size):
            print(f"  [ERROR] Data not ready after {DATA_READY_TIMEOUT_S}s — aborting")
            docker_compose(['down', '-v'], check=False)
            failed.append(size)
            continue

        # 5. Run benchmark
        success = run_benchmark_for_size(size)
        if not success:
            print(f"  [WARN] Benchmark exited non-zero for size={size:,}")

        # 6. Full teardown (removes DB volume so next run starts clean)
        docker_compose(['down', '-v'])

        if success:
            print(f"  [OK] Size {size:,} done. Results: output/scalability/n_{size}/")
        else:
            failed.append(size)

    print(f"\n{'=' * 60}")
    if failed:
        print(f"[DONE] Failures at sizes: {failed}")
        sys.exit(1)
    else:
        print("[DONE] All sizes completed successfully!")
    print(f"{'=' * 60}")


if __name__ == '__main__':
    main()
